"""Write src/akceo/guide.md, the guide to writing decks that ships with akceo.

    uv run python scripts/build_guide.py

The guide is docs/agent/tldr.md, then docs/syntax.md and docs/agent/deck-recipes.md with their
headings one level down, then the demo deck. tests/test_guide.py fails while the committed guide
differs from what this writes.
"""

import re
import tomllib
from collections.abc import Iterator
from pathlib import Path

ROOT = Path(__file__).parents[1]
OUTPUT = ROOT / "src" / "akceo" / "guide.md"
DEMO = ROOT / "examples" / "demo"
FENCE = re.compile(r" {0,3}(`{3,}|~{3,})")
CLOSING = re.compile(r" {0,3}(`{3,}|~{3,})[ \t]*")
HEADING = re.compile(r"^#{1,6}(?=\s|$)")
CODE_SPAN = re.compile(r"(`+).*?\1")
# A link to another file would be relative to the guide, which ships without the docs.
FILE_LINK = re.compile(r"\]\((?![a-z][a-z0-9+.-]*:|#)", re.IGNORECASE)
FILE_REFERENCE = re.compile(r" {0,3}\[[^\]]+\]:\s*(?![a-z][a-z0-9+.-]*:|#)\S", re.IGNORECASE)


def build() -> str:
    title, _, tldr = _read("docs/agent/tldr.md").partition("\n")
    parts = [
        title,
        "<!-- Generated by scripts/build_guide.py from docs/agent/, docs/syntax.md and the demo deck. "
        "Edit those and run it again. -->",
        f"This guide is for akceo {_version()}.",
        tldr.strip(),
        _demoted("docs/syntax.md"),
        _demoted("docs/agent/deck-recipes.md"),
        _example(),
    ]
    return "\n\n".join(parts) + "\n"


def demoted(text: str) -> str:
    """text with every heading one level down. Lines in code fences stay as they are."""
    lines: list[str] = []
    for number, (line, fenced) in enumerate(_lines(text), 1):
        if not fenced and HEADING.match(line):
            if line.startswith("######"):
                raise ValueError(f"line {number}: a level-6 heading has no level below it")
            line = "#" + line
        lines.append(line)
    return "\n".join(lines)


def _demoted(name: str) -> str:
    try:
        return demoted(_read(name))
    except ValueError as e:
        raise SystemExit(f"{name}: {e}") from None


def _lines(text: str) -> Iterator[tuple[str, bool]]:
    """Each line of text, and whether it's part of a code fence. A fence closes on a line of the
    same character, at least as many as opened it, and nothing else but spaces or tabs."""
    fence = ""
    opened = 0
    for number, line in enumerate(text.strip().splitlines(), 1):
        if fence:
            closing = CLOSING.fullmatch(line)
            if closing and closing.group(1)[0] == fence[0] and len(closing.group(1)) >= len(fence):
                fence = ""
            yield line, True
        elif opening := FENCE.match(line):
            fence, opened = opening.group(1), number
            yield line, True
        else:
            yield line, False
    if fence:
        raise ValueError(f"line {opened}: the code fence that opens here isn't closed")


def _example() -> str:
    deck = (DEMO / "deck.md").read_text(encoding="utf-8").strip()
    diagram = (DEMO / "flow.mmd").read_text(encoding="utf-8").strip()
    return (
        "## A worked example\n\n"
        "This is `examples/demo/deck.md` from akceo's repository. It uses every layout. Its diagram, "
        "`flow.mmd`, follows it, and `flow.svg` is a plain SVG image.\n\n"
        f"{_fenced(deck, 'markdown')}\n\n{_fenced(diagram, '')}"
    )


def _fenced(text: str, language: str) -> str:
    longest = max((len(run) for run in re.findall(r"`+", text)), default=0)
    fence = "`" * max(3, longest + 1)
    return f"{fence}{language}\n{text}\n{fence}"


def _read(name: str) -> str:
    text = (ROOT / name).read_text(encoding="utf-8")
    try:
        for line, fenced in _lines(text):
            if not fenced and (FILE_LINK.search(CODE_SPAN.sub("", line)) or FILE_REFERENCE.match(line)):
                raise ValueError("links to another file; link to a #heading or a full URL instead")
    except ValueError as e:
        raise SystemExit(f"{name}: {e}") from None
    return text


def _version() -> str:
    return tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]["version"]


if __name__ == "__main__":
    guide = build()
    OUTPUT.write_text(guide, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({guide.count(chr(10))} lines)")
